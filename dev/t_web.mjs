import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', e => errs.push('pageerror: ' + e.message));
p.on('console', m => { if (m.type() !== 'log' && !m.text().includes('404')) errs.push(m.text()); });
await p.goto('http://localhost:8765/web/index.html');
await p.waitForTimeout(800);
await p.screenshot({ path: '/home/claude/polka/dev/out/w-empty.png' });
const [fc] = await Promise.all([p.waitForEvent('filechooser'), p.click('text=Выбрать файлы')]);
await fc.setFiles(['/home/claude/testbooks/Толстой - Счастливые семьи.epub', '/home/claude/testbooks/cp1251.fb2']);
await p.waitForTimeout(2000);
console.log('books', await p.evaluate(() => window.__polka.library.books.map(b => b.title + ' ' + b.source)));
await p.click('.book >> nth=0'); await p.waitForTimeout(1500);
await p.mouse.click(1200, 400); await p.waitForTimeout(900);
await p.screenshot({ path: '/home/claude/polka/dev/out/w-reader.png' });
console.log('state', await p.evaluate(() => { const r = window.__polka.reader; return { ch: r.ch, page: r.page, spread: r.spread }; }));
console.log(errs.join('\n'));
await b.close();
